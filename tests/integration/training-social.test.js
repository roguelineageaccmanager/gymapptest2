import { it, expect } from 'vitest';
import { makeUser, uniqueName, befriend, adminClient, anonClient } from './helpers.js';
const exercise={name:'Bench',sets:2,target:'8',rest:90,warmupSets:2};
const work={w:'40',r:'8',done:true},warm={w:'20',r:'10',done:true};
it('defaults score sharing on, removes published scores on opt-out and rejects legacy republishing',async()=>{
  const a=await makeUser(uniqueName('share')),b=await makeUser(uniqueName('other'));
  expect((await a.client.from('profiles').select('share_scores').eq('id',a.id).single()).data.share_scores).toBe(true);
  const row={user_id:a.id,workouts_count:1,volume_kg_reps:100};
  expect((await a.client.from('leaderboard_stats').insert(row)).error).toBeNull();
  expect((await a.client.from('profiles').update({share_scores:false}).eq('id',a.id)).error).toBeNull();
  expect((await adminClient().from('leaderboard_stats').select('*').eq('user_id',a.id)).data).toEqual([]);
  expect((await a.client.from('leaderboard_stats').upsert(row)).error?.code).toBe('23514');
  await b.client.from('profiles').update({share_scores:true}).eq('id',a.id);
  expect((await a.client.from('profiles').select('share_scores').eq('id',a.id).single()).data.share_scores).toBe(false);
  expect((await a.client.from('profiles').update({share_scores:true}).eq('id',a.id)).error).toBeNull();
  expect((await a.client.from('leaderboard_stats').upsert(row)).error).toBeNull();
});
it('keeps optional warm-up counts when older clients omit them and accepts an explicit zero',async()=>{
  const a=await makeUser(uniqueName('warm'));
  const plan={workouts:{Push:[exercise]},schedule:{0:'Push'}};
  expect((await a.client.from('workout_plans').insert({user_id:a.id,plan})).error).toBeNull();
  const old={...plan,workouts:{Push:[{name:'Bench',sets:3,target:'8',rest:90}]}};
  const r=await a.client.from('workout_plans').update({plan:old}).eq('user_id',a.id).select('plan').single();
  expect(r.error).toBeNull(); expect(r.data.plan.workouts.Push[0]).toMatchObject({sets:3,warmupSets:2});
  old.workouts.Push[0].warmupSets=0;
  expect((await a.client.from('workout_plans').update({plan:old}).eq('user_id',a.id).select('plan').single()).data.plan.workouts.Push[0].warmupSets).toBe(0);
  old.workouts.Push[0].warmupSets=-1;
  expect((await a.client.from('workout_plans').update({plan:old}).eq('user_id',a.id)).error?.code).toBe('23514');
});
it('preserves logged warm-ups across legacy writes without changing working sets',async()=>{
  const a=await makeUser(uniqueName('hist'));
  const session={id:'warm-session',day:'Push',time:'2026-10-27T12:00:00Z',exercises:[{name:'Bench',target:'8',sets:[work],warmups:[warm]}]};
  const logs={'2026-10-27':[session]};
  expect((await a.client.from('workout_data').insert({user_id:a.id,logs,progress:{}})).error).toBeNull();
  delete session.exercises[0].warmups; session.exercises[0].sets[0]={...work,w:'45'};
  const r=await a.client.from('workout_data').update({logs}).eq('user_id',a.id).select('logs').single();
  expect(r.error).toBeNull(); expect(r.data.logs['2026-10-27'][0].exercises[0]).toMatchObject({sets:[{...work,w:'45'}],warmups:[warm]});
  session.exercises[0].warmups=[];
  expect((await a.client.from('workout_data').update({logs}).eq('user_id',a.id).select('logs').single()).data.logs['2026-10-27'][0].exercises[0].warmups).toEqual([]);
  session.exercises[0].warmups=[{...warm,done:'yes'}];
  expect((await a.client.from('workout_data').update({logs}).eq('user_id',a.id)).error?.code).toBe('23514');
});
it('limits photo reactions to viewers, validates ownership and cascades photo deletion',async()=>{
  const a=await makeUser(uniqueName('pic')),b=await makeUser(uniqueName('pal')),c=await makeUser(uniqueName('out'));
  const friendship=await befriend(a,b);
  const photo=await a.client.from('progress_photos').insert({user_id:a.id,image_data:'data:image/jpeg;base64,AAAA',photo_date:'2026-10-27'}).select('id').single();
  expect(photo.error).toBeNull(); const id=photo.data.id;
  const reaction={photo_id:id,user_id:b.id,emoji:'💪'};
  expect((await b.client.from('progress_photo_reactions').insert(reaction)).error).toBeNull();
  expect((await a.client.from('progress_photo_reactions').insert({...reaction,user_id:a.id})).error).toBeNull();
  const totals=await b.client.rpc('progress_photo_reactions_for',{photo_ids:[id]});
  expect(totals.error).toBeNull(); expect(totals.data).toEqual([{photo_id:id,emoji:'💪',reaction_count:2,mine:true}]);
  expect((await c.client.rpc('progress_photo_reactions_for',{photo_ids:[id]})).data).toEqual([]);
  expect((await c.client.from('progress_photo_reactions').insert({...reaction,user_id:c.id})).error).not.toBeNull();
  expect((await b.client.from('progress_photo_reactions').insert({...reaction,user_id:a.id,emoji:'🔥'})).error).not.toBeNull();
  expect((await b.client.from('progress_photo_reactions').insert({...reaction,emoji:'bad'})).error?.code).toBe('23503');
  expect((await anonClient().rpc('progress_photo_reactions_for',{photo_ids:[id]})).error).not.toBeNull();
  expect((await c.client.from('progress_photo_reactions').select('*')).data).toEqual([]);
  await b.client.from('progress_photo_reactions').delete().eq('user_id',a.id);
  expect((await a.client.rpc('progress_photo_reactions_for',{photo_ids:[id]})).data[0].reaction_count).toBe(2);
  await a.client.from('friend_requests').delete().eq('id',friendship);
  expect((await b.client.rpc('progress_photo_reactions_for',{photo_ids:[id]})).data).toEqual([]);
  await a.client.from('progress_photos').delete().eq('id',id);
  expect((await adminClient().from('progress_photo_reactions').select('*').eq('photo_id',id)).data).toEqual([]);
});
