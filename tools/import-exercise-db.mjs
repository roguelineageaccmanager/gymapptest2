// Rebuild offline data from a locally supplied upstream JSON snapshot.
// Usage: node tools/import-exercise-db.mjs /path/to/exercises.json
// Source revision and license are recorded in vendor/free-exercise-db-NOTICE.txt.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { exerciseId } from '../js/domain/exercises.js';
const matches = JSON.parse(readFileSync(new URL('./exercise-source-matches.json', import.meta.url), 'utf8'));

export const SOURCE_COMMIT = 'f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5';
export function importExercises(source) {
  const seenIds = new Set(), entries = new Map();
  for (const row of source) {
    if (!row.id || seenIds.has(row.id) || !row.name || row.name.length > 80 || !row.primaryMuscles?.length || !Array.isArray(row.instructions) || !Array.isArray(row.images)) throw new Error('Invalid or duplicate source exercise: ' + row.id);
    seenIds.add(row.id);
    // Five upstream records have no instructions. Do not invent technique or
    // add incomplete entries; any matching legacy movements remain untouched.
    if (!row.instructions.length) continue;
    const name = matches[row.name] || row.name;
    const id = exerciseId(name);
    const existing = entries.get(id);
    if (existing) {
      existing.aliases.push(row.name);
      continue;
    }
    // Keep original paths for the matching source movement; never search for
    // illustrations by display name or attach an unrelated variant's picture.
    entries.set(id, { name, sourceId: row.id, sourceName: row.name, aliases: [row.name],
      equipment: row.equipment, primaryMuscles: row.primaryMuscles,
      secondaryMuscles: row.secondaryMuscles, instructions: row.instructions,
      images: row.images, kind: row.category });
  }
  return [...entries.values()];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (!process.argv[2]) throw new Error('Provide the pinned upstream exercises.json snapshot.');
  const source = JSON.parse(readFileSync(process.argv[2], 'utf8'));
  // Prefer the specific illustrations already reviewed in the first expansion.
  const preferred = new Set(['Machine_Bench_Press', 'Standing_Low-Pulley_Deltoid_Raise', 'Thigh_Abductor', 'Thigh_Adductor', 'Cable_Rope_Overhead_Triceps_Extension', 'Cable_Wrist_Curl']);
  source.sort((a, b) => Number(preferred.has(b.id)) - Number(preferred.has(a.id)));
  const rows = importExercises(source);
  const content = '// Generated by tools/import-exercise-db.mjs; see free-exercise-db-NOTICE.txt.\n' +
    `export const SOURCE_COMMIT = '${SOURCE_COMMIT}';\nexport const FREE_EXERCISES = [\n` +
    rows.map(row => '  ' + JSON.stringify(row) + ',').join('\n') + '\n];\n';
  writeFileSync('vendor/free-exercise-db.js', content);
  console.log(`${source.length} source records → ${rows.length} distinct catalogue records.`);
}
